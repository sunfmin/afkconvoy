//! Writes the manual, `docs/manual.md`: what `afkconvoy --help` prints, under
//! a line that says so. The help is the one place afkconvoy is explained, and
//! the page is nothing but it: it is never edited, and the gate fails while it
//! is not what this writes.
//!
//!   cargo run -p afkconvoy --example manual               write the page
//!   cargo run -p afkconvoy --example manual -- --check    fail unless the page is that
//!
//! A path after it names another file than the repository's.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// What writes the page: the line the page and a failed check both give.
const COMMAND: &str = "cargo run -p afkconvoy --example manual";
/// The page, from this package.
const PAGE: &str = "../../docs/manual.md";

fn main() -> ExitCode {
    let mut check = false;
    let mut file = Path::new(env!("CARGO_MANIFEST_DIR")).join(PAGE);
    for arg in std::env::args().skip(1) {
        match arg.as_str() {
            "--check" => check = true,
            path => file = PathBuf::from(path),
        }
    }
    let page = match afkconvoy::manual().manual() {
        Ok(manual) => page(&manual),
        Err(error) => return fail(&format!("the manual is broken: {error}")),
    };
    if !check {
        return match std::fs::write(&file, page) {
            Ok(()) => ExitCode::SUCCESS,
            Err(error) => fail(&format!("{} cannot be written: {error}", file.display())),
        };
    }
    match std::fs::read_to_string(&file) {
        Ok(written) if written == page => ExitCode::SUCCESS,
        Ok(written) => {
            let same = written.lines().zip(page.lines()).take_while(|(a, b)| a == b).count();
            fail(&format!(
                "{} is not what the help generates: it differs at line {}. The page is \
                 never edited: run `{COMMAND}` and commit what it wrote.",
                file.display(),
                same + 1
            ))
        }
        Err(error) => {
            fail(&format!("{} cannot be read ({error}): run `{COMMAND}`.", file.display()))
        }
    }
}

fn fail(why: &str) -> ExitCode {
    eprintln!("manual: {why}");
    ExitCode::FAILURE
}

/// The whole page: the manual, under a comment that says where it is from.
fn page(manual: &str) -> String {
    format!(
        "<!-- Generated by `{COMMAND}`: what `afkconvoy --help` prints. Do not edit it: edit the \
         help where it is written (each command's doc comment, each topic's file), and run \
         that command. -->\n\n{manual}"
    )
}
